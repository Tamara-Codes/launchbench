-- Consolidate "product" and "project" into a single term: project. The two
-- had been used interchangeably since day one (the products table, but a
-- current-project cookie, "Projects are products" comments, UI copy that
-- already said "project" over a productId prop). This migration renames the
-- table, every product_id column, and the dependent indexes, triggers, RLS
-- policies, and the request_agent_job() function to match.

alter table public.products rename to projects;
alter index products_workspace_idx rename to projects_workspace_idx;
alter trigger products_set_updated_at on public.projects rename to projects_set_updated_at;

-- Constraint names auto-generated by the original CREATE TABLE (pkey, the two
-- unique constraints) are an implementation detail; find them by what they
-- are rather than guessing the name, so this cannot fail on a name mismatch.
do $$
declare target record;
begin
  for target in
    select con.conname as constraint_name
    from pg_constraint con
    join pg_class cls on cls.oid = con.conrelid
    join pg_namespace nsp on nsp.oid = cls.relnamespace
    where nsp.nspname = 'public' and cls.relname = 'projects'
      and con.conname like 'products_%'
  loop
    execute format('alter table public.projects rename constraint %I to %I', target.constraint_name, replace(target.constraint_name, 'products_', 'projects_'));
  end loop;
end $$;

drop policy products_member_select on public.projects;
drop policy products_admin_write on public.projects;
create policy projects_member_select on public.projects for select to authenticated using (public.is_workspace_member(workspace_id));
create policy projects_admin_write on public.projects for all to authenticated using (public.is_workspace_admin(workspace_id)) with check (public.is_workspace_admin(workspace_id));

